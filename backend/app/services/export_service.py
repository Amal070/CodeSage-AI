        md.append("## System Statistics & Diagnostics\n")
        md.append("| Metric | Measured Value |")
        md.append("| :--- | :--- |")
        md.append(f"| **Total Source Files** | {stats.total_files:,} files |")
        md.append(f"| **Total Folders** | {stats.total_folders:,} folders |")
        md.append(f"| **Total Lines of Code** | {loc:,} lines |")
