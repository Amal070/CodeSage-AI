        md.append("## Programming Language Distribution\n")
        if analysis.languages:
            md.append("| Language | File Count | Share |")
            md.append("| :--- | :--- | :--- |")
            for lang, count in sorted(analysis.languages.items(), key=lambda x: x[1], reverse=True):
                pct = (count / stats.total_files * 100) if stats.total_files > 0 else 0
                md.append(f"| **{lang}** | {count} | {pct:.1f}% |")
            md.append("")
        else:
            md.append("*No recognized programming languages detected.*\n")

        # 4. Architecture & Dependencies
        md.append("## Architecture & Dependencies\n")
        manifests = sorted(list({p.source for p in dependencies.packages if p.source}))
