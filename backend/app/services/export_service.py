    def generate_api_docs_pdf(self, app: FastAPI) -> bytes:
        """
        Converts the Day 21 API Documentation catalog into an API Specification PDF.
        """
        catalog = api_documentation_service.discover_all_endpoints(app)

        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54,
            title="CodeSage AI - API Specification Reference",
            author="CodeSage AI",
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            "DocTitle", parent=styles["Heading1"], fontSize=20, leading=24, textColor=colors.HexColor("#1e1b4b"), spaceAfter=4, fontName="Helvetica-Bold"
        )
        subtitle_style = ParagraphStyle(
            "DocSubTitle", parent=styles["Normal"], fontSize=9.5, leading=13, textColor=colors.HexColor("#64748b"), spaceAfter=14, fontName="Helvetica"
        )
        tag_style = ParagraphStyle(
            "TagHeading", parent=styles["Heading2"], fontSize=13, leading=17, textColor=colors.HexColor("#0284c7"), spaceBefore=12, spaceAfter=6, fontName="Helvetica-Bold"
        )
        table_cell_bold = ParagraphStyle("CellBold", parent=styles["Normal"], fontSize=8, leading=10, fontName="Helvetica-Bold")
        table_cell_val = ParagraphStyle("CellVal", parent=styles["Normal"], fontSize=8, leading=10, fontName="Helvetica")

        story = []

        story.append(Paragraph("CodeSage AI — API Specification Reference", title_style))
        story.append(Paragraph(f"Comprehensive FastAPI Catalog &bull; {catalog.total_endpoints} Endpoints &bull; Generated {datetime.utcnow().strftime('%B %d, %Y')}", subtitle_style))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#cbd5e1"), spaceBefore=0, spaceAfter=12))

        # Group by tag
        by_tag: Dict[str, List[Any]] = {}
        for ep in catalog.endpoints:
            by_tag.setdefault(ep.tag, []).append(ep)

        for tag, endpoints in by_tag.items():
            story.append(Paragraph(f"Category: {tag}", tag_style))
            ep_data = [[Paragraph("Method", table_cell_bold), Paragraph("Endpoint Path", table_cell_bold), Paragraph("Auth", table_cell_bold), Paragraph("Summary", table_cell_bold)]]
            for ep in endpoints:
                auth_text = "Bearer JWT" if ep.auth_required else "Public"
                ep_data.append([
                    Paragraph(f"<b>{ep.method}</b>", table_cell_val),
                    Paragraph(f"<code>{ep.path}</code>", table_cell_val),
                    Paragraph(auth_text, table_cell_val),
                    Paragraph(ep.summary[:60] if ep.summary else "—", table_cell_val),
                ])
            t = Table(ep_data, colWidths=[0.8 * inch, 2.5 * inch, 1.1 * inch, 2.6 * inch])
            t.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ]))
            story.append(t)
            story.append(Spacer(1, 10))

        doc.build(story, canvasmaker=NumberedCanvas)
        pdf_bytes = buffer.getvalue()
        buffer.close()
        return pdf_bytes


