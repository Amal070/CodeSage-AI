    def _format_size(self, bytes_val: Optional[int]) -> str:
        """Formats byte counts into human-readable strings."""
        if not bytes_val and bytes_val != 0:
            return "0 B"
        if bytes_val < 1024:
            return f"{bytes_val} B"
        if bytes_val < 1024 * 1024:
            return f"{bytes_val / 1024:.1f} KB"
        return f"{bytes_val / (1024 * 1024):.2f} MB"

    def _build_ascii_tree(self, node: Dict[str, Any], prefix: str = "", max_depth: int = 5, current_depth: int = 0) -> List[str]:
        """Recursively formats folder hierarchy into clean ASCII directory tree."""
        if current_depth > max_depth:
            return [prefix + "... (truncated)"]

        lines = []
        children = node.get("children", [])
        total_children = len(children)

        for i, child in enumerate(children):
            is_last = (i == total_children - 1)
            connector = "└── " if is_last else "├── "
            child_prefix = "    " if is_last else "│   "

            name = child.get("name", "unnamed")
            if child.get("type") == "folder":
                lines.append(f"{prefix}{connector}{name}/")
                lines.extend(self._build_ascii_tree(child, prefix + child_prefix, max_depth, current_depth + 1))
            else:
                lines.append(f"{prefix}{connector}{name}")

        return lines

    def _get_project_functions(self, db: Session, project_id: int) -> List[CodeChunk]:
        """Queries stored function and method code chunks for project."""
        stmt = (
            select(CodeChunk)
            .where(
                CodeChunk.project_id == project_id,
                CodeChunk.symbol_type.in_(["function", "method"]),
            )
            .order_by(CodeChunk.file_path, CodeChunk.start_line)
            .limit(100)
        )
        return list(db.scalars(stmt).all())

